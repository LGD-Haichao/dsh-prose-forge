const WORKFLOW = `# 写作流程

六步，按顺序走。材料不够就停在前一步，不要跳过去堆字数。

## 1. 立意
一句话：这份东西写完之后，读者多知道什么、会做什么。写不出这一句，回到用户那里问，别开始写。

## 2. 摸材料
清点手上有什么：代码、日志、文档、数据、别人的说法。
缺关键材料时，两个选择：去查（有出处可查的），或一次问用户不超过三个问题。
不允许用空话把字数凑满。

## 3. 对齐语感
有文风样本（用户旧文、指定作者语料）就先读，再动笔。
没有样本就用常驻契约的默认文体。
需要从语料里提炼风格时，看六层：句子怎么起头、怎么收尾、用不用书面语、怎么称呼人、语气轻重、段落怎么切。

## 4. 出骨架
先给每节一句话主张，确认结构再展开。
用户说"直接写"就跳过确认，但骨架仍要在心里成立。

## 5. 展开
一节一节写。写到某节发现没材料，回头改骨架，不要用形容词填。

## 6. 自检与交稿
跑 prose_check，把标记为重的命中逐条处理。❌ 清零再交。
交稿时说明：改了几处、留了几处、为什么留。
`

