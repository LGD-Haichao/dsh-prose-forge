const DOC = `# 文件写作规范

适用于产出 .md / .docx / .xlsx / .pptx / 报告 / 说明文档。管的是"一份要交给别人读的文件"，不是聊天回复。

## 结构

1. **先定一句话主张。** 这份文件要让人相信什么、知道什么、去做什么。写不出这一句，就先别写正文。
2. **章节数由信息量决定。** 三节够就别写五节。不为了对称把一件事拆成两半，也不为了"完整"补一节常识。
3. **每节首句交代这节干什么**，然后直接给内容。不写"本节将重点阐述……"。
4. **层级不超过三层。** 三级标题还压不住的内容，说明该拆文件了。
5. **篇幅差异反映重要性。** 各节字数差不多，通常说明你在凑数，而不是在按重要性分配。

## 标题

- 写名词或动宾短语："怎么装插件""三个性能瓶颈""接口变更清单"
- 不写：浅谈、浅析、探析、刍议、管窥、视域下、背景下、赋能、驱动、实践与思考
- 同一层级标题结构对齐。全是动宾，或全是名词，不混。

## 表格与列表

- 表格只用于并列或对比：同一组字段、多个对象。
- 单元格里放短语，不放整句；放整句说明该用段落。
- 行数少于 3的"表格"改成句子。
- 列表项必须独立成立，不依赖上一条的语法。

## 引用与数据

- 每个数字要有出处：版本号、命令、文档链接、实测环境。
- 没出处的判断写成判断（"我建议""实测下来"），不要写成客观事实（"研究表明"）。
- 区分：直接引用、转述、自己的推论。三者不混着写。

## 收尾

- 不写"综上所述""总而言之"。结尾停在最后一条实质信息上。
- 需要的话，最后给"下一步"或"还没做的事"，别给情绪。

## 交付

交文件时说明四件事：

1. **路径** — 文件落在哪
2. **做了什么** — 结构、字数、覆盖范围
3. **没做什么** — 哪些没写、为什么
4. **假设** — 用了什么前提，读者改哪里会影响结论

需要 .docx / .xlsx / .pptx 时，调用 office 系列 skill 处理格式，不要自己拼 OOXML。
`

