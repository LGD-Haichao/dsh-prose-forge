/**
 * 取回规则文本。
 * @param {string} part - 段落名，all 表示拼接全部
 * @returns {string | null} 未知段落返回 null
 */
export function lookup(part) {
  if (part === 'all') {
    return PARTS.filter(p => p !== 'all').map(p => MAP[p]).join('\n\n---\n\n')
  }
  return Object.prototype.hasOwnProperty.call(MAP, part) ? MAP[part] : null
}
